create temp table new_cover on commit drop as
  select m.rawg_id, 'https://images.igdb.com/igdb/image/upload/t_cover_big/' || c.image_id || '.jpg' as url
  from public.game_map m join igdb_cover c on c.igdb_id = m.igdb_id;
create unique index on new_cover (rawg_id);

-- Kapak değişimi rozet hesabını ve favori kontrolünü boşuna çalıştırmasın (işlem bitince geri açılır)
alter table public.entries disable trigger entries_badges;
alter table public.entries disable trigger entries_favorites;

update public.entries e set cover = n.url from new_cover n
where e.rawg_id = n.rawg_id and e.type = 'game' and (e.cover ~ '(media\.rawg\.io|howlongtobeat\.com|image\.api\.playstation\.com|store-images\.s-microsoft\.com|cdn\.cloudflare\.steamstatic\.com)' or e.cover is null);
update public.entries set cover = null where cover like '%media.rawg.io%';

alter table public.entries enable trigger entries_badges;
alter table public.entries enable trigger entries_favorites;

update public.list_items e set cover = n.url from new_cover n
where e.rawg_id = n.rawg_id and (e.cover like '%media.rawg.io%' or e.cover is null);
update public.list_items set cover = null where cover like '%media.rawg.io%';

-- Etkinlik seçeneklerindeki kapaklar (sıra korunur)
update public.events ev set options = (
  select jsonb_agg(case
      when x.o->>'cover' like '%media.rawg.io%' and n.url is not null then jsonb_set(x.o, '{cover}', to_jsonb(n.url))
      when x.o->>'cover' like '%media.rawg.io%' then x.o - 'cover'
      else x.o end order by x.i)
  from jsonb_array_elements(ev.options) with ordinality as x(o, i)
  left join new_cover n on n.rawg_id = (x.o->>'rawg_id')::int)
where ev.options::text like '%media.rawg.io%';

