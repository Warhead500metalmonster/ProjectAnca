insert into public.cover_backup (row_key, cover)
  select 'entry:' || id, cover from public.entries where type = 'game' and rawg_id is not null and (cover ~ '(media\.rawg\.io|howlongtobeat\.com|image\.api\.playstation\.com|store-images\.s-microsoft\.com|cdn\.cloudflare\.steamstatic\.com)' or cover is null)
