alter table public.entries disable trigger entries_badges;
alter table public.entries disable trigger entries_favorites;

update public.entries e
set cover = 'https://images.igdb.com/igdb/image/upload/t_cover_big/' || c.image_id || '.jpg'
from public.game_map m join igdb_cover c on c.igdb_id = m.igdb_id
where e.rawg_id = m.rawg_id and e.type = 'game' and e.cover like '%media.rawg.io%'
  and regexp_replace(regexp_replace(lower(e.title), '\s*\((19|20)\d\d\)\s*$', ''), '[^a-z0-9]+', '', 'g') = c.name_key;

alter table public.entries enable trigger entries_badges;
alter table public.entries enable trigger entries_favorites;

